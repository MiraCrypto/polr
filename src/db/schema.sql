CREATE TYPE user_role AS ENUM ('user', 'admin');

CREATE SEQUENCE link_counter_seq
    AS BIGINT
    START WITH 0
    INCREMENT BY 1
    MINVALUE 0
    NO MAXVALUE
    CACHE 1;

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE CHECK (username ~ '^[a-zA-Z0-9_-]+$'),
    password_hash TEXT,
    email         TEXT,
    created_ip    INET,
    role          user_role NOT NULL DEFAULT 'user',
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    api_key       TEXT UNIQUE,
    api_active    BOOLEAN NOT NULL DEFAULT FALSE,
    api_quota     INTEGER NOT NULL DEFAULT 60,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE links (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url     TEXT NOT NULL UNIQUE CHECK (short_url ~ '^[a-zA-Z0-9_-]+$'),
    long_url      TEXT NOT NULL CHECK (char_length(long_url) <= 65535),
    created_ip    INET NOT NULL,
    creator_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
    clicks        BIGINT NOT NULL DEFAULT 0 CHECK (clicks >= 0),
    secret_key    TEXT,
    is_disabled   BOOLEAN NOT NULL DEFAULT FALSE,
    is_custom     BOOLEAN NOT NULL DEFAULT FALSE,
    is_api        BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Fast case-insensitive fallback lookup for custom short URLs
CREATE INDEX links_custom_lower_short_url_idx
    ON links (lower(short_url))
    WHERE is_custom = TRUE;

-- Fast deduplication lookup for non-custom, non-secret links by creator and URL
CREATE INDEX links_dedup_lookup_idx
    ON links (creator_id, md5(long_url))
    WHERE is_custom = FALSE AND secret_key IS NULL;

-- Fast per-minute API rate quota counting
CREATE INDEX links_api_quota_idx
    ON links (creator_id, created_at DESC)
    WHERE is_api = TRUE;

-- Fast user dashboard pagination
CREATE INDEX links_creator_created_idx
    ON links (creator_id, created_at DESC);
